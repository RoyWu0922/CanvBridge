const LANG = () => localStorage.getItem("sc_lang") || "zh";
const t = (key, vars) => {
  let s = (I18N[LANG()] && I18N[LANG()][key]) ?? (I18N.zh[key] ?? key);
  if (vars) for (const k in vars) s = s.replace("{" + k + "}", vars[k]);
  return s;
};
function applyLang() {
  document.title = t("app.title");
  document.documentElement.lang = LANG() === "zh" ? "zh-CN" : "en";
  $$("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  $$("[data-i18n-ph]").forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  $$("[data-i18n-aria]").forEach(el => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  const langBtn = $("btnLang"); if (langBtn) langBtn.textContent = LANG() === "zh" ? "EN" : "中";
  if (typeof fillAlert === "function") {
    /* 选中项文案由 fillAlert() 内联写 t()，所以每个用到它的 <select> 都得在这里重填。
       selTodoAlert 原先漏在名单外 —— 它只在 initTodoTab() 首次进入待办页时填，
       而那个函数有 todoTabInit 守卫、且重填条件又是 `!options.length`，
       所以切语言后它的选项会一直停在旧语言，直到重启应用（同类问题，见 M26 扫描）。 */
    for (const id of ["selAlert", "selSchedAlert", "selDetailAlert", "selTodoAlert"]) {
      const el = $(id);
      const prev = el ? el.value : "";
      fillAlert(id);
      if (el && prev && [...el.options].some(o => o.value === prev)) el.value = prev;
    }
  }
  renderSummaries(); renderFiles(); renderSchedule();
  if (typeof renderTodo === "function") renderTodo();
  if (typeof renderGrades === "function") renderGrades();
  if (typeof renderDiscussions === "function") renderDiscussions();
  if (typeof renderDetail === "function") renderDetail();   // 详情弹层语言切换后重渲
  if (typeof renderQuizzes === "function") renderQuizzes();   // 语言切换后重渲测验分组
  /* 首页三张卡：上面那轮 data-i18n 重设会把它们的行内容打回 home.loading 占位，
     必须重渲（均只在内存数据上工作，不触发网络）。 */
  if (typeof renderHomeAnnounceList === "function") renderHomeAnnounceList();
  if (typeof renderHomeDdlList === "function") renderHomeDdlList();
  if (typeof renderHomeGradeCard === "function") renderHomeGradeCard();
}
